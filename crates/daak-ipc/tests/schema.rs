// proto/ipc.cddl is the schema source of truth. cddl-codegen cannot produce
// the Rust types from it (its output re-tags the externally-tagged serde enums
// as {"StartRequest": {"start": ..}} and stringifies unit variants as
// "ValueText44657669636573", which is not the byte-verified wire), so the enums
// are hand-written serde derives and this test is what keeps them honest:
// real emitted bytes must validate against the CDDL.

use daak_ipc::{IpcEvent, IpcFrame, IpcMessage, IpcRequest, IpcResponse, IPC_VERSION};

fn cddl_src() -> String {
    std::fs::read_to_string(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../proto/ipc.cddl"),
    )
    .unwrap()
}

fn frame_body(msg: &IpcMessage) -> Vec<u8> {
    let mut body = Vec::new();
    ciborium::ser::into_writer(
        &IpcFrame {
            v: IPC_VERSION,
            msg: msg.clone(),
        },
        &mut body,
    )
    .unwrap();
    body
}

fn assert_valid(msg: &IpcMessage) {
    let body = frame_body(msg);
    cddl::validate_cbor_from_slice(&cddl_src(), &body, None)
        .unwrap_or_else(|e| panic!("{msg:?} does not match proto/ipc.cddl: {e:?}"));
}

// The TS client builds every request object by hand and hands it to cbor-x,
// which writes JS property names VERBATIM. So the Rust field names ARE the wire
// contract: there is no rename_all on IpcRequest to paper over a mismatch, and a
// camelCase key on the TS side is a serde ERROR here, not a tolerated variant.
// Start is where that bites hardest -- it is the request that creates the
// engine, so getting its casing wrong makes every later request answer "engine
// not started".
//

// These frames are the EXACT bytes cbor-x produces, generated by
// packages/core/scripts/tmp-encode-probe.mjs into tests/fixtures/ so the hex is
// never hand-transcribed. That pins the cross-language contract exactly rather
// than a hand-written approximation of it.
fn ts_frame(kind: &str) -> Vec<u8> {
    let p =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/ts_start_frame.hex");
    let text = std::fs::read_to_string(&p).unwrap();
    let line = text
        .lines()
        .find(|l| l.starts_with(kind))
        .unwrap_or_else(|| panic!("{kind} missing from {}", p.display()));
    // Lines are "<kind> = <hex>"; split on the separator rather than slicing
    // at a fixed key length.
    let (_, hex) = line
        .split_once('=')
        .unwrap_or_else(|| panic!("{kind} line has no '=' in {}", p.display()));
    let hex = hex.trim().to_string();
    assert_eq!(hex.len() % 2, 0, "hex fixture has an odd length");
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("hex fixture is valid hex"))
        .collect()
}

#[test]
fn the_real_ts_start_frame_decodes_to_start() {
    let frame: IpcFrame = ciborium::from_reader(&ts_frame("snake_case")[..])
        .expect("the bytes cbor-x emits for Start must decode");
    assert_eq!(
        frame.msg,
        IpcMessage::Request(IpcRequest::Start {
            data_dir: "/tmp/x".into(),
            display_name: "daak".into(),
            listen_port: 0,
        })
    );
}

// The guard that matters: the same frame built with camelCase keys -- which is
// what the TS client used to send -- does NOT decode. If someone "fixes" a
// casing mismatch by adding rename_all to IpcRequest, this fails and the wire
// change is forced to be deliberate.
#[test]
fn a_camel_case_start_does_not_decode() {
    let got: Result<IpcFrame, _> = ciborium::from_reader(&ts_frame("camelCase")[..]);
    assert!(
        got.is_err(),
        "camelCase Start decoded; IpcRequest must stay snake_case on the wire"
    );
}

// B1: TransferFilter carries two Option<String> keys whose ABSENCE already
// means "no narrowing". serde's default tolerance for unknown keys is
// therefore not forward compatibility here, it is a silently WIDER query: a
// camelCase `peerDeviceId` (the name the TS type uses) is dropped, the peer
// filter stays None, and the SQL takes its `?2 IS NULL` arm and returns every
// row. deny_unknown_fields makes that a decode error instead.
#[test]
fn a_camel_case_transfer_filter_does_not_decode() {
    // Hand-built rather than serde_json: daak-ipc has no serde_json dependency
    // and this crate must not gain one just to spell a test fixture.
    let body = cbor_filter_frame("peerDeviceId");
    let got: Result<IpcFrame, _> = ciborium::from_reader(&body[..]);
    assert!(
        got.is_err(),
        "camelCase peerDeviceId decoded; a dropped key is a silently whole-DB list"
    );

    // The snake_case spelling the client actually sends still decodes.
    let ok: IpcFrame = ciborium::from_reader(&cbor_filter_frame("peer_device_id")[..])
        .expect("snake_case decodes");
    assert_eq!(
        ok.msg,
        IpcMessage::Request(IpcRequest::ListTransfers {
            filter: Some(daak_ipc::TransferFilter {
                state: Some("queued".into()),
                peer_device_id: Some("00".repeat(16)),
            }),
        })
    );
}

/// `{"v":IPC_VERSION,"msg":{"Request":{"ListTransfers":{"filter":{...}}}}}`
/// with the peer key spelled `peer_key`, which is the whole point: the same
/// frame is built twice and only the casing differs.
fn cbor_filter_frame(peer_key: &str) -> Vec<u8> {
    use ciborium::value::Value;
    let map = |k: &str, v: Value| (Value::Text(k.to_string()), v);
    let filter = Value::Map(vec![
        map("state", Value::Text("queued".into())),
        map(peer_key, Value::Text("00".repeat(16))),
    ]);
    let frame = Value::Map(vec![
        map("v", Value::Integer(IPC_VERSION.into())),
        map(
            "msg",
            Value::Map(vec![map(
                "Request",
                Value::Map(vec![map(
                    "ListTransfers",
                    Value::Map(vec![map("filter", filter)]),
                )]),
            )]),
        ),
    ]);
    let mut body = Vec::new();
    ciborium::ser::into_writer(&frame, &mut body).unwrap();
    body
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[test]
fn every_request_validates_against_the_cddl() {
    let msgs = [
        IpcMessage::Request(IpcRequest::Start {
            data_dir: "/tmp/d".into(),
            display_name: "daak".into(),
            listen_port: 9000,
        }),
        IpcMessage::Request(IpcRequest::Subscribe),
        IpcMessage::Request(IpcRequest::Devices),
        IpcMessage::Request(IpcRequest::Pair {
            addr: "10.0.0.2:9000".into(),
            bundle_cbor: vec![1, 2, 3],
        }),
        IpcMessage::Request(IpcRequest::Send {
            peer_device_id: "00".repeat(16),
            text: Some("hi".into()),
            files: vec!["/tmp/a".into()],
        }),
        IpcMessage::Request(IpcRequest::Send {
            peer_device_id: "00".repeat(16),
            text: None,
            files: vec![],
        }),
        IpcMessage::Request(IpcRequest::Cancel {
            transfer_id: "t1".into(),
        }),
        IpcMessage::Request(IpcRequest::Retry {
            transfer_id: "t1".into(),
        }),
        IpcMessage::Request(IpcRequest::RetryItem {
            transfer_id: "t1".into(),
            item_index: 2,
        }),
        // NEW wire keys, so pinned here for the same reason as SelfProfile
        // below: an arm the cddl does not name validates against nothing and
        // fails only at runtime, on the frame a user triggers by tapping a
        // held-back file. Both take the same (transfer, item) selector, which
        // is what makes the read and the delete name an item identically.
        IpcMessage::Request(IpcRequest::QuarantineReport {
            transfer_id: "t1".into(),
            item_index: 2,
        }),
        // The DISCOVERY half, and a NEW wire key like the two above, so it is
        // pinned for the same reason: a frame the cddl does not name validates
        // against nothing and fails only at runtime.
        IpcMessage::Request(IpcRequest::ListQuarantineReports),
        IpcMessage::Request(IpcRequest::DeleteQuarantined {
            transfer_id: "t1".into(),
            item_index: 2,
        }),
        IpcMessage::Request(IpcRequest::ListTransfers { filter: None }),
        IpcMessage::Request(IpcRequest::ListTransfers {
            filter: Some(daak_ipc::TransferFilter {
                state: Some("queued".into()),
                peer_device_id: Some("00".repeat(16)),
            }),
        }),
        IpcMessage::Request(IpcRequest::ListTransfers {
            filter: Some(daak_ipc::TransferFilter {
                state: None,
                peer_device_id: None,
            }),
        }),
        IpcMessage::Request(IpcRequest::ListThread {
            peer_device_id: "d1".into(),
            limit: 50,
            before: None,
        }),
        IpcMessage::Request(IpcRequest::ListThread {
            peer_device_id: "d1".into(),
            limit: 50,
            before: Some("5:00".into()),
        }),
        IpcMessage::Request(IpcRequest::ListInbox),
        // A unit variant, like Devices/Subscribe -- but it is a NEW wire key, so
        // it has to be pinned here or the cddl can keep refusing the very frame
        // DaemonClientEngine sends after every (re)start without anyone noticing.
        IpcMessage::Request(IpcRequest::SelfProfile),
        IpcMessage::Request(IpcRequest::SetDisplayName {
            name: "renamed".into(),
        }),
        IpcMessage::Request(IpcRequest::SetPresence {
            state: "away".into(),
        }),
        IpcMessage::Request(IpcRequest::ExportDebugBundle {
            // A file NAME: the daemon owns the directory and refuses an
            // absolute path, so this is the shape a real client sends.
            path: "bundle.txt".into(),
        }),
        IpcMessage::Request(IpcRequest::Shutdown),
    ];
    for m in &msgs {
        assert_valid(m);
    }
}

