export type InstallerKind = 'launchd' | 'systemd' | 'windows-service' | 'unsupported';
export type DaemonStatus = 'running' | 'stopped' | 'unknown';

/**
 * The plan's default arm (`return 'systemd'`) answers 'systemd' for every
 * platform it was not told about, including ones with no systemd. Callers
 * feed this straight to an installer path, so an unrecognised platform has to
 * be its own answer rather than a guess. Windows is the third desktop target
 * (Task 9) and is named here even though no installer ships in this phase.
 */
export function installerKind(platform: string): InstallerKind {
  if (platform === 'darwin') return 'launchd';
  if (platform === 'win32') return 'windows-service';
  if (platform === 'linux') return 'systemd';
  return 'unsupported';
}

/** Matches AGENTS.md: launchd label is `dev.darshit.daak.daakd`. */
export const LAUNCHD_LABEL = 'dev.darshit.daak.daakd';

/**
 * `launchctl list` columns are PID, last exit status, Label. This parses the
 * stdout of a system tool, so the label is compared as a whole split field:
 * `com.apple.dev.darshit.daak.daakd` and `dev.darshit.daak.daakd.plist` are
 * other jobs that merely contain ours and must not match.
 *
 * PID is `-` when the job is loaded but not running. Anything else that is
 * not all digits is likewise not a serving pid.
 */
export function parseLaunchctlList(stdout: string, label: string): DaemonStatus {
  for (const line of stdout.split('\n')) {
    const fields = line.trim().split(/\s+/);
    if (fields.length < 3) continue;
    const [pid, , name] = fields;
    if (name !== label) continue;
    return /^\d+$/.test(pid) ? 'running' : 'stopped';
  }
  return 'unknown';
}

// A unit that is loaded-and-not-running (dead, failed, exited) is `stopped`:
// the daemon is not serving, and KeepAlive/Restart=always will bring it back.
// Transitional substates (activating, deactivating, reloading) are neither up
// nor settled, so they are `unknown` rather than a false `stopped`.
const TRANSITIONAL_SUBSTATES = new Set(['activating', 'deactivating', 'reloading']);
// `systemctl show` synthesises LoadState=not-found / SubState=dead for a unit
// name it has never heard of, so a unit that is not loaded is `unknown`, never
// `stopped`. `merged` counts as loaded: that is a unit generated by a drop-in.
const LOADED_LOADSTATES = new Set(['loaded', 'merged']);

/**
 * `systemctl --user show daakd` prints `Key=Value` lines, and every rule here
 * is fail-closed: anything not positively identified as a known-good state is
 * `unknown`, never a guess.
 *
 * LoadState is REQUIRED, not optional. `systemctl show` synthesises
 * SubState=dead for a unit name it has never heard of, so reading SubState
 * without LoadState reports `stopped` for a unit that was never installed. Only
 * `loaded`/`merged` unlock the SubState read at all.
 */
export function parseSystemctlShow(stdout: string): DaemonStatus {
  const load = field(stdout, 'LoadState');
  // REQUIRED: absent is as untrustworthy as not-found. `systemctl show -p
  // SubState` (the plan's own command) emits no LoadState at all, and reading
  // SubState then yields a confident `stopped` for a unit that was never
  // installed.
  if (load === undefined) return 'unknown';
  if (!LOADED_LOADSTATES.has(load)) return 'unknown';

  // Same shape as the LoadState gate: absent, malformed and self-contradictory
  // SubState are all `unknown`, never a guess.
  const first = field(stdout, 'SubState');
  if (first === undefined) return 'unknown';
  if (first === 'running') return 'running';
  if (TRANSITIONAL_SUBSTATES.has(first)) return 'unknown';
  return 'stopped';
}

function lines(stdout: string): string[] {
  return stdout.split('\n').map((l) => l.trim()).filter((l) => l.length > 0);
}

/**
 * One agreed, well-formed value for `key`, or undefined. Undefined covers all
 * three failure shapes and they are deliberately indistinguishable:
 *   - absent: `systemctl show -p SubState` emits no LoadState at all,
 *   - malformed: empty, or carrying trailing junk (`SubState=running;rm -rf`),
 *     rejected by the token pattern rather than matched with `\S+`,
 *   - repeated and in conflict: every copy must agree. The plan's
 *     `first regex hit wins` would silently accept whichever copy came first.
 *
 * A key that appears BOTH well-formed and malformed is rejected outright. That
 * is the case that rules out simply DROPPING malformed copies: with
 * `LoadState=loaded` alongside `LoadState=not-found&x`, dropping the malformed
 * one leaves `loaded`, which unlocks SubState and reports a confident `running`
 * for a unit whose own output claims two different load states. Such output is
 * not a single agreed value, so we are not entitled to pick which one to
 * believe. Measured over 29 inputs, filter-then-agree and reject-on-malformed
 * disagree on exactly this shape.
 */
function field(stdout: string, key: string): string | undefined {
  let agreed: string | undefined;
  for (const line of lines(stdout)) {
    const eq = line.indexOf('=');
    if (eq < 0 || line.slice(0, eq) !== key) continue;
    const value = line.slice(eq + 1);
    if (!/^[A-Za-z0-9_-]+$/.test(value)) return undefined;
    if (agreed !== undefined && agreed !== value) return undefined;
    agreed = value;
  }
  return agreed;
}
