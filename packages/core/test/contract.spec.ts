import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { DaakEngine, DaakEvent, DeviceInfo } from '../src/engine/types';
import { InProcessEngine } from '../src/engine/InProcess';
import { runContractSuite } from './contract-suite';
// Type-only: importing the module for value would run getEnforcing and throw
// outside a React Native runtime.
import type { Spec as NativeDaakSpec } from '../src/NativeDaak';

const METHODS: (keyof DaakEngine)[] = [
  'start', 'stop', 'devices', 'pair', 'send', 'cancel',
  'retry', 'listTransfers', 'listInbox', 'setDisplayName', 'setPresence', 'on',
];

// Compile-time only: adding, removing or renaming a DaakEvent member breaks tsc.
const EVENT_TYPES: Record<DaakEvent['type'], true> = {
  'device.discovered': true,
  'device.state': true,
  'pairing.sas': true,
  'pairing.done': true,
  'transfer.progress': true,
  'transfer.item': true,
  'transfer.done': true,
  'transfer.failed': true,
  'inbox.received': true,
};

// Compile-time only: the native modules (DaakModule.kt, Daak.swift) override
// exactly these methods, so adding, removing or renaming one here breaks tsc on
// the spec and, at build time, the generated NativeDaakSpec.
// getConstants is excluded because RN's TurboModule base declares it optional
// and neither native module implements it; Exclude keeps the pin honest without
// adding a key nothing overrides.
type NativeMethods = Exclude<keyof NativeDaakSpec, 'getConstants'>;
const NATIVE_METHODS: Record<NativeMethods, true> = {
  start: true,
  pairingBundle: true,
  pairWith: true,
  acceptPairing: true,
  sendText: true,
  sendFiles: true,
  listDevices: true,
  cancel: true,
  retry: true,
  localPort: true,
  shutdown: true,
  addListener: true,
  removeListeners: true,
};

export function assertEngineShape(engine: DaakEngine): void {
  const methods: (keyof DaakEngine)[] = METHODS;
  for (const m of methods) expect(typeof engine[m]).toBe('function');
}

describe('contract types', () => {
  it('exposes the documented event union', () => {
    const e: DaakEvent = { type: 'transfer.progress', transferId: 'x', bytesDone: 1, bytesTotal: 2 };
    expect(e.type).toBe('transfer.progress');
  });

  it('pins the engine method set to spec 6.2', () => {
    const exhaustive: Record<keyof DaakEngine, true> = {
      start: true, stop: true, devices: true, pair: true, send: true, cancel: true,
      retry: true, listTransfers: true, listInbox: true, setDisplayName: true,
      setPresence: true, on: true,
    };
    expect(Object.keys(EVENT_TYPES).length).toBe(9);
    expect(Object.keys(exhaustive).length).toBe(METHODS.length);
  });

  it('pins the TurboModule spec the native modules implement', () => {
    expect(Object.keys(NATIVE_METHODS).length).toBe(13);
  });

  it('models a device without fabricating liveness (R11)', () => {
    const discovered: DeviceInfo = { deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' };
    expect(discovered.online).toBeUndefined();
  });

  // I4: the fixture is generated by ffi_event_json (crates/daak-ffi/tests/
  // smoke.rs), so a Rust rename fails the Rust test AND this one. Hand-written
  // literals on each side could agree while both were wrong.
  it('accepts every event the Rust encoder produces (I4)', () => {
    const path = fileURLToPath(new URL('./fixtures/daak-events.json', import.meta.url));
    const fixture: Record<string, unknown> = JSON.parse(readFileSync(path, 'utf8'));
    const entries = Object.entries(fixture);
    expect(entries.length).toBeGreaterThan(0);

    // Required fields per union member, as primitive kinds. Nested objects are
    // listed as 'object' and checked by their own key list below.
    const required: Record<string, Record<string, string>> = {
      'device.discovered': { device: 'object' },
      'device.state': { deviceId: 'string', state: 'string' },
      'pairing.sas': { peerDeviceId: 'string', sas: 'string' },
      'transfer.progress': { transferId: 'string', bytesDone: 'number', bytesTotal: 'number' },
      'transfer.item': { transferId: 'string', itemIndex: 'number', state: 'string' },
      'transfer.done': { transferId: 'string' },
      'transfer.failed': { transferId: 'string', error: 'string' },
      'inbox.received': { payload: 'object' },
    };

    for (const [name, value] of entries) {
      const event = value as Record<string, unknown>;
      const type = event.type;
      expect(typeof type, `${name}.type must be a string`).toBe('string');
      expect(EVENT_TYPES).toHaveProperty(type as string);
      const fields = required[type as string];
      expect(fields, `${name} has type ${String(type)} which the union does not define`).toBeDefined();
      for (const [field, kind] of Object.entries(fields)) {
        expect(typeof event[field], `${name}.${field} must be a ${kind}`).toBe(kind);
      }
    }

    // device.discovered.device is a DeviceInfo, so its own key set is fixed.
    const found = fixture.DeviceFound as { device: Record<string, unknown> };
    for (const [k, kind] of [['deviceId', 'string'], ['name', 'string'], ['addr', 'string'], ['online', 'boolean']]) {
      expect(typeof found.device[k], `device.${k} must be a ${kind}`).toBe(kind);
    }
  });
});

// A native module stand-in. Only the methods a test touches exist; an
// unstubbed one is absent, so calling it is a TypeError rather than a lie.
function fakeNative(over: Partial<NativeDaakSpec> = {}): NativeDaakSpec {
  return {
    start: async () => {},
    shutdown: async () => {},
    localPort: async () => 1234,
    pairingBundle: async () => '{}',
    addListener: () => {},
    removeListeners: () => {},
    ...over,
  } as unknown as NativeDaakSpec;
}

describe('InProcessEngine', () => {
  // A complete-enough native for the shared suite; the unit tests below keep
  // using the deliberately partial fakeNative() so an unstubbed method is
  // still a TypeError there rather than a silent lie.
  runContractSuite('inprocess', async () =>
    new InProcessEngine(fakeNative({ listDevices: async () => '[]' }), () => () => {}),
  );

  it('lets a throwing consumer handler propagate (I1)', () => {
    let emit: (raw: string) => void = () => {};
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      emit = cb;
      return () => {};
    });
    engine.on(() => { throw new Error('handler blew up'); });
    // A consumer that throws must reach whoever emitted, not vanish into the
    // parser's try block.
    expect(() => emit(JSON.stringify({ type: 'transfer.done', transferId: 't1' }))).toThrow('handler blew up');
  });

  it('maps raw event JSON into the typed union (R17)', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb(JSON.stringify({ type: 'transfer.progress', transferId: 't1', bytesDone: 5, bytesTotal: 10 }));
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([
      { type: 'transfer.progress', transferId: 't1', bytesDone: 5, bytesTotal: 10 },
    ]);
  });

  it('drops an unparseable event instead of throwing at the trust boundary', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb('not json');
      cb(JSON.stringify({ nope: 1 }));
      cb(JSON.stringify({ type: 'transfer.done', transferId: 't2' }));
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([{ type: 'transfer.done', transferId: 't2' }]);
  });

  it('resolves the peer addr and hex bundle before pairing (R13)', async () => {
    const calls: unknown[][] = [];
    const native = fakeNative({
      listDevices: async () => JSON.stringify([{ deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' }]),
      pairWith: async (addr: string, cbor: number[]) => {
        calls.push([addr, cbor]);
        return JSON.stringify({ sas: '1-2-3', peer_device_id: 'd1' });
      },
    });
    const engine = new InProcessEngine(native, () => () => {});
    expect(await engine.pair('d1', 'qr', 'a1b2')).toEqual({ sas: '1-2-3' });
    expect(calls).toEqual([['10.0.0.2:9000', [0xa1, 0xb2]]]);
  });

  it('refuses to pair with an unknown device', async () => {
    const native = fakeNative({ listDevices: async () => '[]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('nope', 'qr', 'a1b2')).rejects.toThrow(/nope/);
  });

  it('refuses manual-code pairing: no UDL method exists for it (I3)', async () => {
    const native = fakeNative({ listDevices: async () => '[]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('d1', 'code', '123456')).rejects.toThrow(/manual-code/);
  });

  it('refuses a qr pair with no bundle (m3)', async () => {
    const native = fakeNative({ listDevices: async () => '[{"deviceId":"d1","addr":"10.0.0.2:9000"}]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('d1', 'qr')).rejects.toThrow(/bundle/);
  });

  it('parses the device list and rejects a non-array payload', async () => {
    const good = new InProcessEngine(fakeNative({
      listDevices: async () => '[{"deviceId":"d1","name":"peer","addr":"10.0.0.2:9000"}]',
    }), () => () => {});
    expect(await good.devices()).toEqual([{ deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' }]);

    const bad = new InProcessEngine(fakeNative({ listDevices: async () => '{}' }), () => () => {});
    await expect(bad.devices()).rejects.toThrow(/listDevices/);
  });

  it('routes text-only to sendText and files-only to sendFiles (R7)', async () => {
    const calls: string[] = [];
    const native = fakeNative({
      sendText: async (peer: string, text: string) => { calls.push(`text:${peer}:${text}`); return 'aa11bb22'; },
      sendFiles: async (peer: string, paths: string[]) => { calls.push(`files:${peer}:${paths.join()}`); return 'cc33dd44'; },
    });
    const engine = new InProcessEngine(native, () => () => {});
    // The returned id is the native payload id, verbatim.
    const sent = await engine.send({ peerDeviceId: 'd1', text: 'hi' });
    expect(sent.transferId).toBe('aa11bb22');
    expect(await engine.send({ peerDeviceId: 'd1', files: ['/a', '/b'] })).toEqual({ transferId: 'cc33dd44', queued: true });
    expect(calls).toEqual(['text:d1:hi', 'files:d1:/a,/b']);
  });

  it('refuses a send that carries both text and files (I2)', async () => {
    const engine = new InProcessEngine(fakeNative(), () => () => {});
    await expect(engine.send({ peerDeviceId: 'd1', text: 'hi', files: ['/a'] })).rejects.toThrow(/not both/);
  });

  it('refuses an empty send (M2)', async () => {
    const engine = new InProcessEngine(fakeNative(), () => () => {});
    await expect(engine.send({ peerDeviceId: 'd1' })).rejects.toThrow(/empty/);
    await expect(engine.send({ peerDeviceId: 'd1', text: '' })).rejects.toThrow(/empty/);
    await expect(engine.send({ peerDeviceId: 'd1', files: [] })).rejects.toThrow(/empty/);
  });

  it('accepts the native { event } envelope as well as a bare string (m2)', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb({ event: JSON.stringify({ type: 'transfer.done', transferId: 't3' }) });
      cb({ event: 'not json' });
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([{ type: 'transfer.done', transferId: 't3' }]);
  });
});
