import type { Spec as NativeDaakSpec } from '../src/NativeDaak';

const METHODS: (keyof DaakEngine)[] = [
  'start', 'stop', 'devices', 'pair', 'send', 'cancel',
   'retry', 'quarantineReport', 'deleteQuarantined', 'listQuarantineReports',
   'listTransfers', 'listInbox', 'setDisplayName', 'setPresence', 'on',
  'offerPairing', 'selfProfile',
  'armHostPairing',
  // The per-item re-arm. PARKED and on no screen: `retry` alone cannot reach a
  // held-back item (it re-arms the outbound outbox row, and an inbound
  // transfer has none), and `retryItem` is equally unusable by a user, because
  // the push-only wire protocol has no way to act on it.
  'retryItem',
  // R42f: unpair. A peer this device can never remove is a peer the user can
  // never re-pair, because an open-armed host refuses a device that already has
  // a row.
  'revokePairing',
  // R42p: where a moved received file went. The Inbox opens this field, so a
  // move without it leaves the row pointing at a path that is gone.
  'replaceInboxPaths',
];

// Compile-time only: adding, removing or renaming a DaakEvent member breaks tsc.
const EVENT_TYPES: Record<DaakEvent['type'], true> = {
  'device.discovered': true,
  'device.state': true,
  'pairing.sas': true,
  'pairing.done': true,
  'pairing.revoked': true,
  'transfer.progress': true,
  'transfer.item': true,
  'transfer.done': true,
  'transfer.failed': true,
  'inbox.received': true,
  'peer.incompatible': true,
};

// Compile-time only: the native modules (DaakModule.kt, Daak.swift) override
// exactly these methods, so adding, removing or renaming one here breaks tsc on
// the spec and, at build time, the generated NativeDaakSpec.
// getConstants is excluded because RN's TurboModule base declares it optional
// and neither native module implements it; Exclude keeps the pin honest without
// adding a key nothing overrides.
type NativeMethods = Exclude<keyof NativeDaakSpec, 'getConstants'>;
const NATIVE_METHODS: Record<NativeMethods, true> = {
  start: true,
  pairingBundle: true,
  offerPairing: true,
  armHostPairing: true,
  pairWith: true,
  acceptPairing: true,
  sendText: true,
  sendFiles: true,
  listDevices: true,
  revokePairing: true,
  backgroundWake: true,
  replaceInboxPaths: true,
  cancel: true,
  retry: true,
  retryItem: true,
  quarantineReport: true,
  deleteQuarantined: true,
  listQuarantineReports: true,
  listTransfers: true,
  listInbox: true,
  selfProfile: true,
  setDisplayName: true,
  setPresence: true,
  localPort: true,
  shutdown: true,
  addListener: true,
  removeListeners: true,
};

export function assertEngineShape(engine: DaakEngine): void {
  const methods: (keyof DaakEngine)[] = METHODS;
  for (const m of methods) expect(typeof engine[m]).toBe('function');
}

describe('contract types', () => {
  it('exposes the documented event union', () => {
    const e: DaakEvent = { type: 'transfer.progress', transferId: 'x', bytesDone: 1, bytesTotal: 2 };
    expect(e.type).toBe('transfer.progress');
  });

  it('pins the engine method set to spec 6.2', () => {
    const exhaustive: Record<keyof DaakEngine, true> = {
      start: true, stop: true, devices: true, pair: true, send: true, cancel: true,
      revokePairing: true,
      replaceInboxPaths: true,
      retry: true, quarantineReport: true, deleteQuarantined: true,
      listQuarantineReports: true,
      listTransfers: true, listInbox: true, selfProfile: true, setDisplayName: true,
      setPresence: true, on: true, offerPairing: true, armHostPairing: true,
      retryItem: true, backgroundWake: true,
    };
    // 11 = the union's 11 members. peer.incompatible is pinned by tsc alone,
    // via this Record's exhaustiveness, and NOT by the fixture below -- which
    // has 9 entries for a reason that has nothing to do with the encoder.
    // ffi_event_json DOES emit it: the FfiEvent::IncompatiblePeer arm at
    // crates/daak-ffi/src/lib.rs:847 writes "type": "peer.incompatible", and
    // to_ffi_event (lib.rs:967) feeds that arm from the engine's own event. The
    // gap is in the fixture GENERATOR, not the encoder: sample_events in
    // crates/daak-ffi/tests/smoke.rs:490 hand-lists 9 variants and never
    // constructs an IncompatiblePeer one, so the checked-in fixture -- which
    // that ignored regenerator (smoke.rs:599) writes -- stays at 9 keys. The
    // I4 test below therefore covers the other 9, not every arm of the encoder;
    // its own comment calls it "the fixture is generated by ffi_event_json",
    // which is true of the 9 but not exhaustive over the encoder. smoke.rs:487
    // already flags the hand-listing (a new FfiEvent variant is not caught
    // there), so the tenth is a KNOWN, recorded gap -- not a dead event path.
    expect(Object.keys(EVENT_TYPES).length).toBe(10);
    expect(Object.keys(exhaustive).length).toBe(METHODS.length);
  });

  it('pins the TurboModule spec the native modules implement', () => {
    // 24 = the 23 'interface DaakEngine' methods in crates/daak-ffi/src/daak.udl
    // (constructors excluded), MINUS ffi_event_json, which no JS caller can
    // reach -- the native modules call it on the uniffi handle themselves
    // (DaakModule.kt:229, Daak.swift:234) to encode an FfiEvent for sendEvent,
    // so it has no TurboModule method and never crosses the bridge; PLUS
    // addListener/removeListeners, which are RCTEventEmitter's and codegen base
    // class's, declared on the Spec because RN's TurboModule requires them,
    // and with no UDL counterpart at all.
    //     23 UDL - 1 ffi_event_json + 2 listeners = 24
    // armHostPairing is NOT an extra on top of the UDL count: it is one of the
    // 23 (arm_host_pairing, added in 5d00ec5). It used to be counted twice --
    // once inside the UDL total and again as "+ armHostPairing" -- which landed
    // on the right number only by coincidence (19+1 and 19-1+2 are both 20).
    // This form cannot drift that way again. A count bump here means a native
    // method was added without a decision here.
    // 25: the 24 above plus revoke_pairing (R42f), which is a UDL method AND a
    // TurboModule override on all three native modules.
    expect(Object.keys(NATIVE_METHODS).length).toBe(26);
  });

  it('models a device without fabricating liveness (R11)', () => {
    const discovered: DeviceInfo = { deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' };
    expect(discovered.online).toBeUndefined();
  });

  // I4: the fixture is generated by ffi_event_json (crates/daak-ffi/tests/
  // smoke.rs), so a Rust rename fails the Rust test AND this one. Hand-written
  // literals on each side could agree while both were wrong.
  it('accepts every event the Rust encoder produces (I4)', () => {
    const path = fileURLToPath(new URL('./fixtures/daak-events.json', import.meta.url));
    const fixture: Record<string, unknown> = JSON.parse(readFileSync(path, 'utf8'));
    const entries = Object.entries(fixture);
    expect(entries.length).toBeGreaterThan(0);

    // Required fields per union member, as primitive kinds. Nested objects are
    // listed as 'object' and checked by their own key list below.
    const required: Record<string, Record<string, string>> = {
      'device.discovered': { device: 'object' },
      'device.state': { deviceId: 'string', state: 'string' },
      'pairing.sas': { peerDeviceId: 'string', sas: 'string' },
      'pairing.done': { deviceId: 'string' },
      'transfer.progress': { transferId: 'string', bytesDone: 'number', bytesTotal: 'number' },
      'transfer.item': { transferId: 'string', itemIndex: 'number', state: 'string' },
      'transfer.done': { transferId: 'string' },
      'transfer.failed': { transferId: 'string', error: 'string' },
      'inbox.received': { payload: 'object' },
    };

    for (const [name, value] of entries) {
      const event = value as Record<string, unknown>;
      const type = event.type;
      expect(typeof type, `${name}.type must be a string`).toBe('string');
      expect(EVENT_TYPES).toHaveProperty(type as string);
      const fields = required[type as string];
      expect(fields, `${name} has type ${String(type)} which the union does not define`).toBeDefined();
      for (const [field, kind] of Object.entries(fields)) {
        expect(typeof event[field], `${name}.${field} must be a ${kind}`).toBe(kind);
      }
    }

    // device.discovered.device is a DeviceInfo, so its own key set is fixed.
    const found = fixture.DeviceFound as { device: Record<string, unknown> };
    for (const [k, kind] of [['deviceId', 'string'], ['name', 'string'], ['addr', 'string'], ['online', 'boolean']]) {
      expect(typeof found.device[k], `device.${k} must be a ${kind}`).toBe(kind);
    }
  });
});

// A native module stand-in. Only the methods a test touches exist; an
// unstubbed one is absent, so calling it is a TypeError rather than a lie.
function fakeNative(over: Partial<NativeDaakSpec> = {}): NativeDaakSpec {
  // setDisplayName and selfProfile are STATEFUL on purpose, and the state
  // (`let name`, read back by selfProfile) is not decoration: the shared suite
  // does `setDisplayName('renamed')` and then asserts selfProfile().name
  // matches /renamed/ (contract-suite.ts:143), so a selfProfile that returned a
  // constant would fail that assertion. Do NOT 'simplify' these two back into
  // constant-returning stubs -- it breaks the shared suite. The rename resolves
  // against the LAN, so the fake keeps the string verbatim and the suite demands
  // only a prefix match, never the exact resolved name.
  let name = 'Test Device';
  return {
    start: async () => {},
    shutdown: async () => {},
    localPort: async () => 1234,
    pairingBundle: async () => '{}',
    // R-T10-3: an unknown id is an ERROR, not a silent success. The fake has to
    // model that, or the shared suite's rejection assertion would be testing
    // the fake rather than the contract.
    cancel: async (id: string) => {
      if (!/^[0-9a-f]{32}$/i.test(id)) throw new Error(`bad transfer id: ${id}`);
      throw new Error(`no outbox row for transfer ${id}`);
    },
    retry: async (id: string) => {
      if (!/^[0-9a-f]{32}$/i.test(id)) throw new Error(`bad transfer id: ${id}`);
      throw new Error(`no outbox row for transfer ${id}`);
    },
    listTransfers: async () => '[]',
    listInbox: async () => '[]',
    // The quarantine surface, in the BASE rather than in the suite's
    // fakeNative({...}) override, because what these three model is the shape
    // of the BRIDGE and not one test's data: a fake that has just been started
    // holds nothing, and an id nobody ever wrote names no row. That is the
    // state the shared suite creates, so pinning it here is pinning the
    // contract rather than a fixture -- the same reason listTransfers and
    // listInbox answer '[]' here. An override would also be the wrong tool: the
    // unit tests below never call these three, so a suite-only stub would leave
    // the base fake lying about a surface it does not implement, which is the
    // exact failure the armHostPairing note below is about.
    //
    // The rejections are load-bearing, not filler: the shared suite asserts
    // that a read of an unknown item REJECTS, because behind it every lookup
    // matches zero rows (require_item in crates/daak-core/src/engine.rs) and
    // without the explicit guard a report would come back as a screen of
    // invented nulls. A fake that resolved would make that assertion test the
    // fake instead of the bridge. listQuarantineReports must be a JSON ARRAY,
    // because the bridge rejects a non-array payload rather than returning it
    // typed.
    quarantineReport: async () => { throw new Error('no quarantined item'); },
    listQuarantineReports: async () => '[]',
    deleteQuarantined: async () => { throw new Error('no quarantined item'); },
    setDisplayName: async (next: string) => { name = next; },
    setPresence: async () => {},
    // baseName tracks the same state. The fake has no LAN, so no collision
    // resolves and the base name equals the advertised one.
    selfProfile: async () =>
      JSON.stringify({ name, baseName: name, deviceId: 'dd'.repeat(16) }),
    // The host arm (spec 3.3 Mode A). It takes no bundle, so there is nothing
    // for the fake to validate -- and a missing method here is a TypeError in
    // the shared suite rather than a silent pass, which is the point of the
    // partial/unit split.
    armHostPairing: async () => {},
    addListener: () => {},
    removeListeners: () => {},
    ...over,
  } as unknown as NativeDaakSpec;
}

describe('InProcessEngine', () => {
  // A complete-enough native for the shared suite; the unit tests below keep
  // using the deliberately partial fakeNative() so an unstubbed method is
  // still a TypeError there rather than a silent lie.
  runContractSuite('inprocess', async () =>
    new InProcessEngine(fakeNative({ listDevices: async () => '[]' }), () => () => {}),
  );

  it('lets a throwing consumer handler propagate (I1)', () => {
    let emit: (raw: string) => void = () => {};
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      emit = cb;
      return () => {};
    });
    engine.on(() => { throw new Error('handler blew up'); });
    // A consumer that throws must reach whoever emitted, not vanish into the
    // parser's try block.
    expect(() => emit(JSON.stringify({ type: 'transfer.done', transferId: 't1' }))).toThrow('handler blew up');
  });

  it('maps raw event JSON into the typed union (R17)', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb(JSON.stringify({ type: 'transfer.progress', transferId: 't1', bytesDone: 5, bytesTotal: 10 }));
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([
      { type: 'transfer.progress', transferId: 't1', bytesDone: 5, bytesTotal: 10 },
    ]);
  });

  it('drops an unparseable event instead of throwing at the trust boundary', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb('not json');
      cb(JSON.stringify({ nope: 1 }));
      cb(JSON.stringify({ type: 'transfer.done', transferId: 't2' }));
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([{ type: 'transfer.done', transferId: 't2' }]);
  });

  it('resolves the peer addr and hex bundle before pairing (R13)', async () => {
    const calls: unknown[][] = [];
    const native = fakeNative({
      listDevices: async () => JSON.stringify([{ deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' }]),
      pairWith: async (addr: string, cbor: number[]) => {
        calls.push([addr, cbor]);
        return JSON.stringify({ sas: '1-2-3', peer_device_id: 'd1' });
      },
    });
    const engine = new InProcessEngine(native, () => () => {});
    expect(await engine.pair('d1', 'qr', 'a1b2')).toEqual({ sas: '1-2-3' });
    expect(calls).toEqual([['10.0.0.2:9000', [0xa1, 0xb2]]]);
  });

  it('refuses to pair with an unknown device', async () => {
    const native = fakeNative({ listDevices: async () => '[]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('nope', 'qr', 'a1b2')).rejects.toThrow(/nope/);
  });

  it('refuses manual-code pairing: no UDL method exists for it (I3)', async () => {
    const native = fakeNative({ listDevices: async () => '[]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('d1', 'code', '123456')).rejects.toThrow(/manual-code/);
  });

  it('refuses a qr pair with no bundle (m3)', async () => {
    const native = fakeNative({ listDevices: async () => '[{"deviceId":"d1","addr":"10.0.0.2:9000"}]' });
    const engine = new InProcessEngine(native, () => () => {});
    await expect(engine.pair('d1', 'qr')).rejects.toThrow(/bundle/);
  });

  // C2. The host arm: the scanned joiner's bundle CBOR reaches the native
  // offer_pairing as the SAME decoded bytes `pair` sends the other way, and
  // an un-decodable hex string is refused at the boundary rather than
  // half-decoded into the engine.
  it('arms the host with the scanned bundle bytes, and refuses non-hex', async () => {
    const seen: number[][] = [];
    const native = fakeNative({
      offerPairing: async (cbor: number[]) => {
        seen.push(cbor);
      },
    });
    const engine = new InProcessEngine(native, () => () => {});
    await engine.offerPairing('ccdd');
    expect(seen).toEqual([[0xcc, 0xdd]]);
    await expect(engine.offerPairing('xyz')).rejects.toThrow(/hex/);
  });

  // The host arm a real user reaches (spec 3.3 Mode A). Two facts: it takes NO
  // argument, and it crosses to the native module with no payload at all --
  // there is no bundle to hex-decode, which is exactly why the previous
  // bundle-taking arm was unreachable for a real user.
  it('arms the host with no bundle and no payload crossing the bridge', async () => {
    const calls: string[] = [];
    const engine = new InProcessEngine(fakeNative({
      armHostPairing: async () => { calls.push('armHostPairing'); },
    }), () => () => {});
    await engine.armHostPairing();
    expect(calls).toEqual(['armHostPairing']);
  });

  it('parses the device list and rejects a non-array payload', async () => {
    const good = new InProcessEngine(fakeNative({
      listDevices: async () => '[{"deviceId":"d1","name":"peer","addr":"10.0.0.2:9000"}]',
    }), () => () => {});
    expect(await good.devices()).toEqual([{ deviceId: 'd1', name: 'peer', addr: '10.0.0.2:9000' }]);

    const bad = new InProcessEngine(fakeNative({ listDevices: async () => '{}' }), () => () => {});
    await expect(bad.devices()).rejects.toThrow(/listDevices/);
  });

  it('routes text-only to sendText and files-only to sendFiles (R7)', async () => {
    const calls: string[] = [];
    const native = fakeNative({
      sendText: async (peer: string, text: string) => { calls.push(`text:${peer}:${text}`); return 'aa11bb22'; },
      sendFiles: async (peer: string, paths: string[]) => { calls.push(`files:${peer}:${paths.join()}`); return 'cc33dd44'; },
    });
    const engine = new InProcessEngine(native, () => () => {});
    // The returned id is the native payload id, verbatim.
    const sent = await engine.send({ peerDeviceId: 'd1', text: 'hi' });
    expect(sent.transferId).toBe('aa11bb22');
    expect(await engine.send({ peerDeviceId: 'd1', files: ['/a', '/b'] })).toEqual({ transferId: 'cc33dd44', queued: true });
    expect(calls).toEqual(['text:d1:hi', 'files:d1:/a,/b']);
  });

  it('refuses a send that carries both text and files (I2)', async () => {
    const engine = new InProcessEngine(fakeNative(), () => () => {});
    await expect(engine.send({ peerDeviceId: 'd1', text: 'hi', files: ['/a'] })).rejects.toThrow(/not both/);
  });

  it('refuses an empty send (M2)', async () => {
    const engine = new InProcessEngine(fakeNative(), () => () => {});
    await expect(engine.send({ peerDeviceId: 'd1' })).rejects.toThrow(/empty/);
    await expect(engine.send({ peerDeviceId: 'd1', text: '' })).rejects.toThrow(/empty/);
    await expect(engine.send({ peerDeviceId: 'd1', files: [] })).rejects.toThrow(/empty/);
  });

  it('accepts the native { event } envelope as well as a bare string (m2)', () => {
    const emitted: DaakEvent[] = [];
    const engine = new InProcessEngine(fakeNative(), (cb) => {
      cb({ event: JSON.stringify({ type: 'transfer.done', transferId: 't3' }) });
      cb({ event: 'not json' });
      return () => {};
    });
    engine.on((e) => emitted.push(e));
    expect(emitted).toEqual([{ type: 'transfer.done', transferId: 't3' }]);
  });

  it('forwards cancel, retry, profile and list methods to the native engine', async () => {
    const calls: unknown[][] = [];
    const native = fakeNative({
      cancel: async (id: string) => { calls.push(['cancel', id]); },
      retry: async (id: string) => { calls.push(['retry', id]); },
      listTransfers: async (filterJson: string) => { calls.push(['listTransfers', filterJson]); return '[]'; },
      listInbox: async () => { calls.push(['listInbox']); return '[]'; },
      setDisplayName: async (name: string) => { calls.push(['setDisplayName', name]); },
      setPresence: async (state: string) => { calls.push(['setPresence', state]); },
    });
    const engine = new InProcessEngine(native, () => () => {});
    await engine.cancel('00'.repeat(16));
    await engine.retry('00'.repeat(16));
    await engine.setDisplayName('renamed');
    await engine.setPresence('away');
    expect(await engine.listTransfers()).toEqual([]);
    expect(await engine.listTransfers({ state: 'pending' })).toEqual([]);
    expect(await engine.listInbox()).toEqual([]);
    expect(calls).toEqual([
      ['cancel', '00'.repeat(16)],
      ['retry', '00'.repeat(16)],
      ['setDisplayName', 'renamed'],
      ['setPresence', 'away'],
      // An absent filter is "{}" on the UDL boundary, which the Rust parser
      // reads as None (list everything).
      ['listTransfers', '{}'],
      ['listTransfers', '{"state":"pending"}'],
      ['listInbox'],
    ]);
  });

  it('keeps a corrupt saved_paths row as null rather than coercing it to []', async () => {
    // SHOULD-FIX 4. Both engines map an unparseable saved_paths JSON blob to
    // `null`, because `[]` is a REAL answer ("this payload saved no files") and
    // a corrupt row must stay distinguishable from it. The TS type is
    // string[] | null to match; if it were string[], `?? []` here would be the
    // bug and this test would fail.
    const engine = new InProcessEngine(
      fakeNative({
        listInbox: async () =>
          JSON.stringify([
            {
              payloadId: 'aa'.repeat(16),
              transferId: 'aa'.repeat(16),
              peerDeviceId: 'bb'.repeat(16),
              kind: 'text',
              itemCount: 1,
              summary: 'hi',
              receivedAt: 0,
              savedPaths: null,
            },
          ]),
      }),
      () => () => {},
    );
    const [row] = await engine.listInbox();
    expect(row.savedPaths).toBeNull();
  });

  it('rejects a list payload that is not an array instead of returning it typed', async () => {
    const engine = new InProcessEngine(
      fakeNative({ listTransfers: async () => '{}', listInbox: async () => 'null' }),
      () => () => {},
    );
    await expect(engine.listTransfers()).rejects.toThrow(/listTransfers/);
    await expect(engine.listInbox()).rejects.toThrow(/listInbox/);
  });

  it('reports queued: true for a share to an offline peer, because the outbox took it', async () => {
    // The native send returns a PAYLOAD ID with no delivery information, so
    // `queued` is the only honest thing the return type can say: the row is
    // durable and will drain on reconnect. Delivery is transfer.done /
    // transfer.failed, not this return value.
    const engine = new InProcessEngine(
      fakeNative({ sendText: async () => 'aa'.repeat(16) }),
      () => () => {},
    );
    expect(await engine.send({ peerDeviceId: 'ab'.repeat(16), text: 'offline' })).toEqual({
      transferId: 'aa'.repeat(16),
      queued: true,
    });
  });
});
