#import "AppDelegate.h"

#import <React/RCTBundleURLProvider.h>
#import <React/RCTLinkingManager.h>
// Daak-Swift.h declares DaakNotificationDelegate as conforming to
// UNUserNotificationCenterDelegate, but the generated header only pulls that
// framework in behind `#if __has_feature(objc_modules)`, and that feature test
// is FALSE for Objective-C++ no matter what -fmodules says (verified with
// clang -x objective-c++ -fmodules: the same file compiled as -x objective-c
// reports the feature present). AppDelegate.mm is the one file that both
// includes the generated header and names that protocol, so this import is the
// whole fix. An @import would not help: modules are off for ObjC++ here too.
#import <UserNotifications/UserNotifications.h>
// Generated by the Swift compiler for the app target's own Swift sources
// (DaakIntentBridge.swift etc.), which is where DaakNotificationDelegate lives.
#import "Daak-Swift.h"

@implementation AppDelegate

- (BOOL)application:(UIApplication *)application didFinishLaunchingWithOptions:(NSDictionary *)launchOptions
{
  self.moduleName = @"Daak";
  // You can add your custom initial props in the dictionary below.
  // They will be passed down to the ViewController used by React Native.
  self.initialProps = @{};

  // Installed here, NOT from JS. On a killed app iOS delivers a tapped
  // notification response at launch, before the bridge exists: a delegate set
  // from registerCategories is nil in exactly that case, so the tap was lost.
  // DaakNotificationDelegate.stashes the action in the App Group and
  // DaakNotify.consumePendingAction hands it to JS once it is up.
  [DaakNotificationDelegate install];

  // Installed here for the same reason, and BEFORE anything can be delivered:
  // iOS launches the process to run a BGTask, and the rn-bgsched TurboModule
  // does not exist until the bridge has booted. Registered from JS it would
  // miss exactly the cold launch it exists for. DaakBgLaunch is the ONLY
  // registrant -- registering the same identifier twice makes the FIRST
  // registration the real one, so a second, no-op owner silently wins.
  [DaakBgLaunch install];

  return [super application:application didFinishLaunchingWithOptions:launchOptions];
}

// daak:// links (a pairing QR, a daak://send target, the share extension)
// arrive here and must reach apps/mobile/src/deeplink.ts.
//
// THE MISSING HANDLER WAS A CRASH, NOT A DEAD BUTTON. Info.plist declares
// LSSupportsOpeningDocumentsInPlace, and UIKit turns that key plus an absent
// application:openURL:options: into a fatal NSInternalInconsistencyException:
//
//   *** Terminating app due to uncaught exception
//   'NSInternalInconsistencyException', reason: 'Application has
//   LSSupportsOpeningDocumentsInPlace key, but doesn't implement
//   application:openURL:options: on delegate <AppDelegate: 0x...>'
//
// So every daak://pair link killed the app on the way in. Nothing ever paired,
// the send screen refused every peer at "peer is not paired", and the parser
// and manifest suites stayed green because both only pin registration.
//
// RCTLinkingManager is the one forwarder that works: it stores the cold-launch
// initialURL and posts the `url` event, which is exactly what
// apps/mobile/src/deeplink.ts reads through Linking.getInitialURL() and
// Linking.addEventListener('url'). A second native emitter would be invisible
// to both. The macOS delegate already does this in
// apps/desktop/macos/Daak-macOS/AppDelegate.mm, so both hosts agree.
- (BOOL)application:(UIApplication *)application
            openURL:(NSURL *)url
            options:(NSDictionary<UIApplicationOpenURLOptionsKey, id> *)options
{
  return [RCTLinkingManager application:application openURL:url options:options];
}

- (NSURL *)sourceURLForBridge:(RCTBridge *)bridge
{
  return [self bundleURL];
}

- (NSURL *)bundleURL
{
#if DEBUG
  return [[RCTBundleURLProvider sharedSettings] jsBundleURLForBundleRoot:@"index"];
#else
  return [[NSBundle mainBundle] URLForResource:@"main" withExtension:@"jsbundle"];
#endif
}

@end
