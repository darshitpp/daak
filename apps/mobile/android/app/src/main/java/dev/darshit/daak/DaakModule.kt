package dev.darshit.daak

import android.content.Context
import android.net.wifi.WifiManager
import android.util.Log
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.bridge.ReadableArray
import com.facebook.react.module.annotations.ReactModule
import com.facebook.react.modules.core.DeviceEventManagerModule
import java.io.File
import java.util.concurrent.CountDownLatch
import uniffi.daak_ffi.DaakEngine
import uniffi.daak_ffi.EventSink
import uniffi.daak_ffi.FfiEvent

// NativeDaakSpec is GENERATED by react-native codegen from
// packages/core/src/NativeDaak.ts and lands in dev.darshit.daak because
// apps/mobile/package.json sets codegenConfig.android.javaPackageName.
// DaakEngine/EventSink/FfiEvent are GENERATED by uniffi_bindgen 0.28.3 from
// crates/daak-ffi/src/daak.udl into the uniffi.daak_ffi package (derived from
// the crate name daak-ffi). There are no JNI symbols to declare: the generated
// bindings reach the Rust cdylib through JNA.
//
// ponytail: the generated bindings load the native library through JNA, and
// findLibraryName() hardcodes "uniffi_daak_ffi" -- but this crate's cdylib is
// libdaak_ffi.so. Phase 5 packaging must either ship the .so under the name the
// bindings load or set uniffi.component.daak_ffi.libraryOverride; until then the
// first engine call throws UnsatisfiedLinkError. The ceiling is that JNA must
// also be on the classpath and the cdylib packaged for every ABI. Upgrade path:
// Phase 5 packaging -- add JNA to build.gradle and either
// generate JNI bindings instead (uniffi::uniffi_bindgen main/java) or set
// uniffi.component.daak_ffi.libraryOverride. The iOS
// equivalent is that daak_ffiFFI.h and daak_ffiFFI.modulemap must be added to
// the Xcode target alongside the Swift file.
@ReactModule(name = DaakModule.NAME)
class DaakModule(reactContext: ReactApplicationContext) :
    NativeDaakSpec(reactContext), EventSink {

    companion object { const val NAME = "Daak" }

    private val lock = Any()
    private var engine: DaakEngine? = null
    private var multicastLock: WifiManager.MulticastLock? = null
    // start() runs on its own Thread and takes seconds on a cold process, while
    // every screen calls devices() on mount. This latch is how a call that
    // arrives mid-start waits for the engine instead of being told it does not
    // exist. It counts down in a finally, so a FAILED start releases the wait
    // too and the waiter gets the engine's own error rather than a hang.
    private val startedLatch = CountDownLatch(1)
    private var startAttempted = false
    // `engine = e` happens BEFORE e.start(), so a non-null field does NOT mean
    // the Rust engine is up: crates/daak-ffi assigns its own slot at the END of
    // DaakEngine.start(). A call in that window used to call straight through and
    // get 'engine not started' back from Rust for an engine that was merely
    // still starting. This flag is the real readiness signal.
    private var startComplete = false

    // Android filters multicast packets out of Wi-Fi RX to save power, so an app
    // that holds no MulticastLock receives ZERO bytes on 224.0.0.251:5353 (the
    // mDNS browse) or on the presence group 239.255.67.68:53535. The engine does
    // exactly that, so without this lock the peer list is permanently empty and
    // every send dies at the "peer is not paired" gate in crates/daak-core/src/engine.rs.
    // CHANGE_WIFI_MULTICAST_STATE is already declared in AndroidManifest.xml.
    //
    // Reference counting is OFF so this is a plain on/off switch: a second start()
    // must not stack a count that no code path knows how to release.
    private fun acquireMulticastLock() {
        val wifi = reactApplicationContext.applicationContext
            .getSystemService(Context.WIFI_SERVICE) as WifiManager
        synchronized(lock) {
            if (multicastLock?.isHeld == true) return
            multicastLock = wifi.createMulticastLock("$NAME.mdns").also {
                it.setReferenceCounted(false)
                it.acquire()
            }
        }
    }

    private fun releaseMulticastLock() {
        synchronized(lock) {
            multicastLock?.takeIf { it.isHeld }?.release()
            multicastLock = null
        }
    }

    override fun getName() = NAME

    @ReactMethod
    override fun start(dataDir: String, displayName: String, listenPort: Double, promise: Promise) {
        Thread {
            synchronized(lock) { startAttempted = true }
            try {
                // BEFORE the engine binds its sockets: the browse starts inside
                // e.start(), and a packet dropped before the lock is held is a
                // peer the device never learns about.
                acquireMulticastLock()
                // R43: dataDir is IGNORED, not honoured-when-non-empty.
                // InProcessEngine.start() takes no arguments and hardcodes '',
                // so the "use the incoming dir when it is set" branch would be
                // dead code today and a sandbox escape hatch the day the frozen
                // TS path changes. Resolving it here is the only way the
                // invariant "the engine data dir is inside the app sandbox"
                // holds no matter what a caller sends.
                val dir = File(reactApplicationContext.filesDir, "daak")
                // R40(c): a keystore failure REJECTS this start. There is no
                // fallback to a plaintext file store: one that silently
                // regenerates the Ed25519 identity and re-pairs the device as
                // a new one, with no error anywhere the user can see.
                val e = DaakEngine.newWithStore(KeystoreSecureStore(reactApplicationContext), this)
                // BEFORE e.start(), which blocks. A caller that wakes during
                // startup now reaches a real engine object, and it waits on
                // startedLatch inside its own call rather than being told the
                // engine is missing.
                synchronized(lock) { engine = e }
                e.start(dir.absolutePath, displayName, listenPort.toInt().toUShort())
                synchronized(lock) { startComplete = true }
                Log.i(NAME, "engine start returned; port=${e.localPort()}")
                promise.resolve(null)
            } catch (t: Throwable) {
                // A start failure used to be invisible: the engine field was
                // only cleared by shutdown, so the waiter woke, saw a null,
                // and reported the generic "engine not started" -- which names
                // the wrong problem entirely. The real cause is here.
                Log.e(NAME, "engine start failed", t)
                synchronized(lock) { if (engine?.let { true } == true) engine = null }
                promise.reject("E_ENGINE", t)
            } finally {
                startedLatch.countDown()
            }
        }.start()
    }

    @ReactMethod
    override fun pairingBundle(promise: Promise) = resolve(promise) { handle().pairingBundle() }

    @ReactMethod
    override fun pairWith(addr: String, bundleCbor: ReadableArray, promise: Promise) {
        val bytes = List(bundleCbor.size()) { bundleCbor.getInt(it).toUByte() }
        resolve(promise) { handle().pairWith(addr, bytes) }
    }

    // C2 RE-ARM path: the caller holds the peer's bundle, so this takes the
    // same bytes as pairWith and arms the accept slot for that peer.
    @ReactMethod
    override fun offerPairing(bundleCbor: ReadableArray, promise: Promise) {
        val bytes = List(bundleCbor.size()) { bundleCbor.getInt(it).toUByte() }
        // The trailing null is load-bearing: this generated method returns
        // Unit, and PromiseImpl.resolve(Unit) throws inside RN's fromJavaArgs.
        resolve(promise) { handle().offerPairing(bytes); null }
    }

    // C2, second review: the host arm spec 3.3 Mode A actually needs. The QR
    // flow is asymmetric -- only the JOINER scans, so the host never holds the
    // joiner's bundle and an arm requiring one is unreachable. No argument: the
    // engine learns the peer's identity in-band and verifies it in the Noise XX
    // handshake, and the user comparing the two SAS values is what binds it to a
    // human. See PendingArm::Open in crates/daak-core.
    @ReactMethod
    override fun armHostPairing(promise: Promise) =
        // The trailing null is load-bearing for the same reason as
        // offerPairing(): this generated method returns Unit.
        resolve(promise) { handle().armHostPairing(); null }

    @ReactMethod
    override fun acceptPairing(promise: Promise) = resolve(promise) { handle().acceptPairing() }

    @ReactMethod
    override fun sendText(peerId: String, text: String, promise: Promise) =
        resolve(promise) { handle().sendText(peerId, text) }

    @ReactMethod
    override fun sendFiles(peerId: String, paths: ReadableArray, promise: Promise) {
        val list = List(paths.size()) { paths.getString(it)!! }
        resolve(promise) { handle().sendFiles(peerId, list) }
    }

    @ReactMethod
    override fun listDevices(promise: Promise) = resolve(promise) { handle().listDevices() }

    @ReactMethod
    override fun cancel(transferId: String, promise: Promise) =
        // The trailing null is load-bearing: these generated methods return
        // Unit, and PromiseImpl.resolve(Unit) throws inside RN's fromJavaArgs.
        resolve(promise) { handle().cancel(transferId); null }

    @ReactMethod
    override fun retry(transferId: String, promise: Promise) =
        resolve(promise) { handle().retry(transferId); null }

    @ReactMethod
    override fun revokePairing(deviceId: String, promise: Promise) =
        // The trailing null is load-bearing, the same as cancel()/retry().
        resolve(promise) { handle().revokePairing(deviceId); null }

    @ReactMethod
    override fun replaceInboxPaths(payloadId: String, paths: List<String>, promise: Promise) =
        resolve(promise) { handle().replaceInboxPaths(payloadId, paths); null }

    @ReactMethod
    override fun retryItem(transferId: String, itemIndex: Double, promise: Promise) =
        // The trailing null is load-bearing for the same reason as retry():
        // this generated method returns Unit, and PromiseImpl.resolve throws.
        resolve(promise) { handle().retryItem(transferId, itemIndexArg(itemIndex)); null }

    @ReactMethod
    override fun quarantineReport(transferId: String, itemIndex: Double, promise: Promise) =
        resolve(promise) { handle().quarantineReport(transferId, itemIndexArg(itemIndex)) }

    @ReactMethod
    override fun listQuarantineReports(promise: Promise) =
        resolve(promise) { handle().listQuarantineReports() }

    @ReactMethod
    override fun deleteQuarantined(transferId: String, itemIndex: Double, promise: Promise) =
        resolve(promise) { handle().deleteQuarantined(transferId, itemIndexArg(itemIndex)); null }

    @ReactMethod
    override fun listTransfers(filterJson: String, promise: Promise) =
        resolve(promise) { handle().listTransfers(filterJson) }

    @ReactMethod
    override fun listInbox(promise: Promise) = resolve(promise) { handle().listInbox() }

    @ReactMethod
    override fun selfProfile(promise: Promise) = resolve(promise) { handle().selfProfile() }

    @ReactMethod
    override fun setDisplayName(name: String, promise: Promise) =
        resolve(promise) { handle().setDisplayName(name); null }

    @ReactMethod
    override fun setPresence(state: String, promise: Promise) =
        resolve(promise) { handle().setPresence(state); null }

    @ReactMethod
    override fun localPort(promise: Promise) = resolve(promise) { handle().localPort().toDouble() }

    @ReactMethod
    override fun shutdown(promise: Promise) = resolve(promise) {
        val e = synchronized(lock) { engine.also { engine = null } }
        e?.shutdown()
        releaseMulticastLock()
        null
    }

    // Both are required by the generated spec. This module emits through
    // RCTDeviceEventEmitter directly, so there is no listener registry to keep.
    override fun addListener(eventName: String) = Unit

    override fun removeListeners(count: Double) = Unit

    // Every engine call blocks on the engine's tokio runtime, so none of it runs
    // on the JS or main thread. T is nullable so the Unit-returning methods can
    // resolve null rather than the Unit that Promise.resolve rejects.
    // Not `inline`, same reason DaakClipboardModule's onMain is not: the
    // lambdas below contain non-local returns (`return null`, `?: throw`),
    // which Kotlin forbids in an inlined lambda. Thread is already created per
    // call, so inlining saved nothing.
    private fun <T> resolve(promise: Promise, block: () -> T?) {
        Thread {
            try { promise.resolve(block()) }
            catch (t: Throwable) { promise.reject("E_DAAK", t) }
        }.start()
    }

    // Waits for an in-flight start. startAttempted distinguishes "not ready
    // yet" (wait) from "never asked" (throw): without it the first render of
    // any screen would block forever on a latch nobody counts down.
    private fun handle(): DaakEngine {
        val waiting = synchronized(lock) { startAttempted && !startComplete }
        if (waiting) {
            try {
                startedLatch.await()
            } catch (e: InterruptedException) {
                Thread.currentThread().interrupt()
                throw IllegalStateException("interrupted waiting for the engine to start", e)
            }
        }
        return synchronized(lock) { engine }
            ?: throw IllegalStateException("engine not started; call start() first")
    }

    // The UDL's "u32 item_index" reaches Kotlin as UInt, but JS has no integers,
    // so codegen gives this method a Double. The two hops between them are both
    // lossy in ways that do NOT announce themselves, which is why this validates
    // instead of casting:
    //   Double.toInt() SATURATES. NaN -> 0, +Inf -> Int.MAX_VALUE, -Inf ->
    //     Int.MIN_VALUE, and 4.29e9 -> Int.MAX_VALUE. Nothing throws.
    //   Int.toUInt() REINTERPRETS, it does not range-check. -1 becomes
    //     4294967295, a different, perfectly plausible item index.
    // So the naive itemIndex.toInt().toUInt() silently retries, reads or deletes
    // the WRONG quarantine item -- worse than an error, because the caller sees a
    // success. An item index is a count, so anything that is not a non-negative
    // whole number inside UInt's range is a caller bug and is rejected here.
    // The throw is caught by resolve(), which rejects the promise with E_DAAK,
    // so JS gets a normal Error instead of a Kotlin exception crossing the bridge.
    private fun itemIndexArg(itemIndex: Double): UInt {
        require(itemIndex.isFinite() && itemIndex >= 0.0) {
            "itemIndex must be a finite non-negative number, got $itemIndex"
        }
        require(itemIndex == Math.floor(itemIndex) && itemIndex <= UINT_MAX) {
            "itemIndex must be a whole number in 0..$UINT_MAX, got $itemIndex"
        }
        return itemIndex.toInt().toUInt()
    }

    // 4294967295.0. Spelled out rather than UInt.MAX_VALUE.toDouble() because
    // the latter is the constant's own value rounded to Double, which is exact
    // here but reads as if it were approximate.
    private val UINT_MAX = 4294967295.0

    // UniFFI EventSink callback, invoked on a Rust thread. The UDL hands us an
    // FfiEvent rather than a string, so the generated ffiEventJson turns it
    // into the DaakEvent JSON that packages/core/src/engine/types.ts defines.
    override fun onEvent(event: FfiEvent) {
        try {
            val map = Arguments.createMap()
            map.putString("event", handle().ffiEventJson(event))
            reactApplicationContext
                .getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
                .emit("DaakEvent", map)
        } catch (t: Throwable) {
            // A Rust thread cannot reject a JS promise, so the only honest
            // channel for a conversion failure is the log.
            Log.e(NAME, "ffiEventJson failed for $event", t)
        }
    }
}
